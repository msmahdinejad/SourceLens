class StudioArtifactStore:
    """Durable SQLite lifecycle store beside private workspace media."""

    _terminal_statuses = {"ready", "failed", "cancelled", "interrupted"}
    _active_statuses = {"queued", "gathering", "drafting", "generating"}

    def __init__(self, workspaces_root: Path) -> None:
        self.root = workspaces_root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.database_path = self.root / "studio-lifecycle.sqlite3"
        self._lock = threading.RLock()
        self._initialize()
        self._migrate_json()

    def _connect(self) -> sqlite3.Connection:
        connection = sqlite3.connect(self.database_path, timeout=30)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA journal_mode=WAL")
        connection.execute("PRAGMA busy_timeout=30000")
        connection.execute("PRAGMA foreign_keys=ON")
        return connection

    def _initialize(self) -> None:
        with self._connect() as connection:
            connection.executescript(
                """
                CREATE TABLE IF NOT EXISTS artifacts (
                    workspace_id TEXT NOT NULL,
                    artifact_id TEXT NOT NULL,
                    artifact_type TEXT NOT NULL,
                    status TEXT NOT NULL,
                    stage TEXT NOT NULL,
                    progress INTEGER NOT NULL,
                    revision INTEGER NOT NULL,
                    payload TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL,
                    PRIMARY KEY (workspace_id, artifact_id)
                );
                CREATE INDEX IF NOT EXISTS artifacts_workspace_updated
                    ON artifacts(workspace_id, updated_at DESC, artifact_id DESC);
                CREATE TABLE IF NOT EXISTS jobs (
                    workspace_id TEXT NOT NULL,
                    artifact_id TEXT NOT NULL,
                    status TEXT NOT NULL,
                    stage TEXT NOT NULL,
                    progress INTEGER NOT NULL,
                    revision INTEGER NOT NULL,
                    cancel_requested INTEGER NOT NULL DEFAULT 0,
                    checkpoint_safe INTEGER NOT NULL DEFAULT 0,
                    lease_owner TEXT,
                    lease_expires_at REAL,
                    heartbeat_at TEXT,
                    attempt_count INTEGER NOT NULL DEFAULT 0,
                    updated_at TEXT NOT NULL,
                    PRIMARY KEY (workspace_id, artifact_id)
                );
                CREATE TABLE IF NOT EXISTS attempts (
                    attempt_id INTEGER PRIMARY KEY AUTOINCREMENT,
                    workspace_id TEXT NOT NULL,
                    artifact_id TEXT NOT NULL,
                    stage TEXT NOT NULL,
                    provider TEXT,
                    model TEXT,
                    status TEXT NOT NULL,
                    started_at TEXT NOT NULL,
                    finished_at TEXT,
                    safe_error TEXT
                );
                CREATE TABLE IF NOT EXISTS events (
                    sequence INTEGER PRIMARY KEY AUTOINCREMENT,
                    workspace_id TEXT NOT NULL,
                    artifact_id TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    stage TEXT NOT NULL,
                    status TEXT NOT NULL,
                    message TEXT NOT NULL,
                    current_units INTEGER,
                    total_units INTEGER,
                    duration_ms REAL,
                    cache_hit INTEGER,
                    byte_count INTEGER,
                    attempt INTEGER,
                    details TEXT NOT NULL DEFAULT '{}'
                );
                CREATE INDEX IF NOT EXISTS events_artifact_sequence
                    ON events(workspace_id, artifact_id, sequence);
                """
            )
            event_columns = {
                row[1] for row in connection.execute("PRAGMA table_info(events)")
            }
            for name, kind in (
                ("duration_ms", "REAL"),
                ("cache_hit", "INTEGER"),
                ("byte_count", "INTEGER"),
                ("attempt", "INTEGER"),
            ):
                if name not in event_columns:
                    connection.execute(f"ALTER TABLE events ADD COLUMN {name} {kind}")

    def _migrate_json(self) -> None:
        """Import legacy metadata once, retaining source JSON as a rollback path."""
        for path in self.root.glob("*/artifacts/artifact-*.json"):
            try:
                artifact = StudioArtifact.model_validate_json(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            with self._connect() as connection:
                exists = connection.execute(
                    "SELECT 1 FROM artifacts WHERE workspace_id = ? AND artifact_id = ?",
                    (artifact.workspace_id, artifact.artifact_id),
                ).fetchone()
            if exists is None:
                self.save(artifact)
            self._migrate_legacy_events(artifact)

    def _migrate_legacy_events(self, artifact: StudioArtifact) -> None:
        legacy_events = artifact.data.get("events")
        if not isinstance(legacy_events, list) or not legacy_events:
            return
        with self._lock, self._connect() as connection:
            existing = connection.execute(
                "SELECT 1 FROM events WHERE workspace_id = ? AND artifact_id = ? LIMIT 1",
                (artifact.workspace_id, artifact.artifact_id),
            ).fetchone()
            if existing is not None:
                return
            rows = []
            for item in legacy_events:
                if not isinstance(item, dict):
                    continue
                kind = str(item.get("kind") or "legacy")[:80]
                status = (
                    "failed"
                    if "failed" in kind
                    else "cancelled"
                    if "cancel" in kind
                    else "completed"
                    if kind.endswith("ready")
                    else "queued"
                    if kind.endswith("queued")
                    else "running"
                )
                progress = item.get("progress")
                rows.append(
                    (
                        artifact.workspace_id,
                        artifact.artifact_id,
                        str(item.get("created_at") or artifact.created_at),
                        kind,
                        status,
                        str(item.get("message") or kind.replace("_", " "))[:500],
                        max(0, min(100, int(progress))) if progress is not None else None,
                        100 if progress is not None else None,
                        json.dumps(
                            _safe_event_details(
                                {"legacy_event_id": str(item.get("event_id") or "")}
                            ),
                            ensure_ascii=False,
                        ),
                    )
                )
            connection.executemany(
                """
                INSERT INTO events(
                    workspace_id, artifact_id, timestamp, stage, status, message,
                    current_units, total_units, details
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                rows,
            )

    def save(self, artifact: StudioArtifact) -> StudioArtifact:
        self._path(artifact.workspace_id, artifact.artifact_id).parent.mkdir(
            parents=True, exist_ok=True
        )
        with self._lock, self._connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            row = connection.execute(
                """SELECT payload, revision FROM artifacts
                WHERE workspace_id = ? AND artifact_id = ?""",
                (artifact.workspace_id, artifact.artifact_id),
            ).fetchone()
            current = StudioArtifact.model_validate_json(row["payload"]) if row else None
            if current is not None:
                stale = artifact.revision < current.revision
                stale_cancellation_of_active = (
                    artifact.status == "cancelled"
                    and current.status in self._active_statuses
                )
                if (
                    current.status == "cancelled"
                    and artifact.status != "cancelled"
                    or stale
                    and not stale_cancellation_of_active
                ):
                    return current
            revision = (int(row["revision"]) if row else 0) + 1
            progress = artifact.progress
            data = dict(artifact.data)
            if current is not None:
                is_retry_reset = (
                    current.status in {"failed", "interrupted"}
                    and artifact.status == "queued"
                    and artifact.stage == "retry_queued"
                )
                if not is_retry_reset:
                    progress = max(current.progress, progress)
                data = {**current.data, **data}
                if current.data.get("cancel_requested"):
                    data["cancel_requested"] = True
            updated = artifact.model_copy(
                update={
                    "data": data,
                    "progress": progress,
                    "revision": revision,
                    "updated_at": utc_now(),
                }
            )
            payload = updated.model_dump_json()
            connection.execute(
                """
                INSERT INTO artifacts(
                    workspace_id, artifact_id, artifact_type, status, stage, progress,
                    revision, payload, created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(workspace_id, artifact_id) DO UPDATE SET
                    artifact_type=excluded.artifact_type,
                    status=excluded.status,
                    stage=excluded.stage,
                    progress=excluded.progress,
                    revision=excluded.revision,
                    payload=excluded.payload,
                    updated_at=excluded.updated_at
                """,
                (
                    updated.workspace_id,
                    updated.artifact_id,
                    updated.artifact_type,
                    updated.status,
                    updated.stage,
                    updated.progress,
                    revision,
                    payload,
                    updated.created_at,
                    updated.updated_at,
                ),
            )
            cancel_requested = int(
                updated.status == "cancelled" or bool(updated.data.get("cancel_requested"))
            )
            connection.execute(
                """
                INSERT INTO jobs(
                    workspace_id, artifact_id, status, stage, progress, revision,
                    cancel_requested, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(workspace_id, artifact_id) DO UPDATE SET
                    status=excluded.status,
                    stage=excluded.stage,
                    progress=excluded.progress,
                    revision=excluded.revision,
                    cancel_requested=MAX(jobs.cancel_requested, excluded.cancel_requested),
                    updated_at=excluded.updated_at
                """,
                (
                    updated.workspace_id,
                    updated.artifact_id,
                    updated.status,
                    updated.stage,
                    updated.progress,
                    revision,
                    cancel_requested,
                    updated.updated_at,
                ),
            )
            return updated

    def get(self, workspace_id: str, artifact_id: str) -> StudioArtifact:
        self._path(workspace_id, artifact_id)
        with self._connect() as connection:
            row = connection.execute(
                "SELECT payload FROM artifacts WHERE workspace_id = ? AND artifact_id = ?",
                (workspace_id, artifact_id),
            ).fetchone()
        if row is None:
            raise KeyError(f"Unknown studio artifact: {artifact_id}")
        return StudioArtifact.model_validate_json(row["payload"])

    def list(self, workspace_id: str) -> list[StudioArtifact]:
        return self.list_page(workspace_id, limit=500)["items"]

    def list_page(self, workspace_id: str, *, limit: int = 50, cursor: int = 0) -> dict[str, Any]:
        self._directory(workspace_id)
        limit = max(1, min(100, int(limit)))
        cursor = max(0, int(cursor))
        with self._connect() as connection:
            rows = connection.execute(
                """
                SELECT payload FROM artifacts WHERE workspace_id = ?
                ORDER BY created_at DESC, artifact_id DESC LIMIT ? OFFSET ?
                """,
                (workspace_id, limit + 1, cursor),
            ).fetchall()
        items = [StudioArtifact.model_validate_json(row["payload"]) for row in rows[:limit]]
        return {
            "items": items,
            "next_cursor": cursor + limit if len(rows) > limit else None,
        }

    def request_cancel(self, workspace_id: str, artifact_id: str) -> StudioArtifact:
        current = self.get(workspace_id, artifact_id)
        if current.status == "cancelled":
            return current
        cancelled = self.save(
            current.model_copy(
                update={
                    "status": "cancelled",
                    "stage": "cancelled",
                    "error": None,
                    "data": {**current.data, "cancel_requested": True},
                }
            )
        )
        self.record_event(
            workspace_id,
            artifact_id,
            stage="cancel",
            status="cancelled",
            message="Cancellation confirmed",
            current=cancelled.progress,
            total=100,
        )
        return cancelled

    def record_event(
        self,
        workspace_id: str,
        artifact_id: str,
        *,
        stage: str,
        status: str,
        message: str,
        current: int | None = None,
        total: int | None = None,
        duration_ms: float | None = None,
        cache_hit: bool | None = None,
        byte_count: int | None = None,
        attempt: int | None = None,
        details: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        self._path(workspace_id, artifact_id)
        timestamp = utc_now()
        with self._lock, self._connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            row = connection.execute(
                """SELECT payload FROM artifacts
                WHERE workspace_id = ? AND artifact_id = ?""",
                (workspace_id, artifact_id),
            ).fetchone()
            if row is None:
                raise KeyError(artifact_id)
            artifact = StudioArtifact.model_validate_json(row["payload"])
            safe_details = _safe_event_details(details or {})
            safe_details["artifact_progress"] = artifact.progress
            safe_details["artifact_status"] = artifact.status
            safe_details["artifact_revision"] = artifact.revision
            cursor = connection.execute(
                """
                INSERT INTO events(
                    workspace_id, artifact_id, timestamp, stage, status, message,
                    current_units, total_units, duration_ms, cache_hit, byte_count,
                    attempt, details
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    workspace_id,
                    artifact_id,
                    timestamp,
                    str(stage)[:80],
                    str(status)[:40],
                    str(message)[:500],
                    current,
                    total,
                    max(0.0, float(duration_ms)) if duration_ms is not None else None,
                    int(cache_hit) if cache_hit is not None else None,
                    max(0, int(byte_count)) if byte_count is not None else None,
                    max(1, int(attempt)) if attempt is not None else None,
                    json.dumps(safe_details, ensure_ascii=False),
                ),
            )
            sequence = int(cursor.lastrowid)
        return {
            "sequence": sequence,
            "timestamp": timestamp,
            "stage": str(stage)[:80],
            "status": str(status)[:40],
            "message": str(message)[:500],
            "current": current,
            "total": total,
            "duration_ms": max(0.0, float(duration_ms)) if duration_ms is not None else None,
            "cache_hit": bool(cache_hit) if cache_hit is not None else None,
            "byte_count": max(0, int(byte_count)) if byte_count is not None else None,
            "attempt": max(1, int(attempt)) if attempt is not None else None,
            "details": safe_details,
        }

    def events(
        self,
        workspace_id: str,
        artifact_id: str,
        *,
        after: int = 0,
        limit: int = 200,
        tail: bool = False,
    ) -> list[dict[str, Any]]:
        self._path(workspace_id, artifact_id)
        with self._connect() as connection:
            rows = connection.execute(
                """
                SELECT sequence, timestamp, stage, status, message, current_units,
                       total_units, duration_ms, cache_hit, byte_count, attempt, details
                FROM events
                WHERE workspace_id = ? AND artifact_id = ? AND sequence > ?
                ORDER BY sequence """
                + ("DESC" if tail else "ASC")
                + """ LIMIT ?
                """,
                (workspace_id, artifact_id, max(0, int(after)), max(1, min(500, int(limit)))),
            ).fetchall()
        events = [
            {
                "sequence": int(row["sequence"]),
                "timestamp": row["timestamp"],
                "stage": row["stage"],
                "status": row["status"],
                "message": row["message"],
                "current": row["current_units"],
                "total": row["total_units"],
                "duration_ms": row["duration_ms"],
                "cache_hit": (
                    bool(row["cache_hit"]) if row["cache_hit"] is not None else None
                ),
                "byte_count": row["byte_count"],
                "attempt": row["attempt"],
                "details": json.loads(row["details"]),
            }
            for row in rows
        ]
        return list(reversed(events)) if tail else events

    def acquire_lease(
        self,
        workspace_id: str,
        artifact_id: str,
        *,
        owner: str,
        checkpoint_safe: bool = False,
        lease_seconds: float = 30.0,
    ) -> dict[str, Any]:
        self.get(workspace_id, artifact_id)
        now = utc_now()
        with self._connect() as connection:
            connection.execute(
                """
                UPDATE jobs SET lease_owner = ?, lease_expires_at = ?, heartbeat_at = ?,
                    checkpoint_safe = ?, updated_at = ?
                WHERE workspace_id = ? AND artifact_id = ?
                """,
                (
                    str(owner)[:120],
                    time.time() + max(1.0, float(lease_seconds)),
                    now,
                    int(checkpoint_safe),
                    now,
                    workspace_id,
                    artifact_id,
                ),
            )
        return self.job(workspace_id, artifact_id)

    def heartbeat(self, workspace_id: str, artifact_id: str, *, owner: str) -> None:
        now = utc_now()
        with self._connect() as connection:
            cursor = connection.execute(
                """
                UPDATE jobs SET heartbeat_at = ?, lease_expires_at = ?, updated_at = ?
                WHERE workspace_id = ? AND artifact_id = ? AND lease_owner = ?
                """,
                (now, time.time() + 30.0, now, workspace_id, artifact_id, owner),
            )
        if cursor.rowcount != 1:
            raise ValueError("Studio lease is not owned by this worker")

    def release_lease(
        self, workspace_id: str, artifact_id: str, *, owner: str | None = None
    ) -> None:
        with self._connect() as connection:
            if owner is None:
                connection.execute(
                    """UPDATE jobs SET lease_owner = NULL, lease_expires_at = NULL
                    WHERE workspace_id = ? AND artifact_id = ?""",
                    (workspace_id, artifact_id),
                )
            else:
                connection.execute(
                    """UPDATE jobs SET lease_owner = NULL, lease_expires_at = NULL
                    WHERE workspace_id = ? AND artifact_id = ? AND lease_owner = ?""",
                    (workspace_id, artifact_id, owner),
                )

    def begin_attempt(
        self,
        workspace_id: str,
        artifact_id: str,
        *,
        stage: str,
        provider: str | None = None,
        model: str | None = None,
    ) -> int:
        self.get(workspace_id, artifact_id)
        with self._connect() as connection:
            cursor = connection.execute(
                """
                INSERT INTO attempts(
                    workspace_id, artifact_id, stage, provider, model, status, started_at
                ) VALUES (?, ?, ?, ?, ?, 'running', ?)
                """,
                (workspace_id, artifact_id, stage, provider, model, utc_now()),
            )
            connection.execute(
                """
                UPDATE jobs SET attempt_count = attempt_count + 1, updated_at = ?
                WHERE workspace_id = ? AND artifact_id = ?
                """,
                (utc_now(), workspace_id, artifact_id),
            )
            return int(cursor.lastrowid)

    def finish_attempt(
        self, attempt_id: int, *, status: str, safe_error: str | None = None
    ) -> None:
        with self._connect() as connection:
            cursor = connection.execute(
                """
                UPDATE attempts SET status = ?, finished_at = ?, safe_error = ?
                WHERE attempt_id = ? AND status = 'running'
                """,
                (status, utc_now(), (safe_error or "")[:500] or None, int(attempt_id)),
            )
        if cursor.rowcount != 1:
            raise ValueError("Studio attempt is already finished or unknown")

    def job(self, workspace_id: str, artifact_id: str) -> dict[str, Any]:
        with self._connect() as connection:
            row = connection.execute(
                "SELECT * FROM jobs WHERE workspace_id = ? AND artifact_id = ?",
                (workspace_id, artifact_id),
            ).fetchone()
        if row is None:
            raise KeyError(f"Unknown studio job: {artifact_id}")
        return dict(row)

    def reconcile_startup(self) -> dict[str, list[str]]:
        resume: list[str] = []
        interrupted: list[str] = []
        with self._connect() as connection:
            rows = connection.execute(
                """
                SELECT workspace_id, artifact_id, checkpoint_safe FROM jobs
                WHERE status IN ('queued', 'gathering', 'drafting', 'generating')
                  AND lease_owner IS NOT NULL
                ORDER BY artifact_id
                """
            ).fetchall()
        for row in rows:
            workspace_id = str(row["workspace_id"])
            artifact_id = str(row["artifact_id"])
            artifact = self.get(workspace_id, artifact_id)
            if bool(row["checkpoint_safe"]):
                resumed = self.save(
                    artifact.model_copy(update={"status": "queued", "stage": "resume_queued"})
                )
                resume.append(resumed.artifact_id)
                self.release_lease(workspace_id, artifact_id)
                continue
            stopped = self.save(
                artifact.model_copy(
                    update={
                        "status": "interrupted",
                        "stage": "interrupted",
                        "data": {**artifact.data, "retryable": True},
                        "error": "Application stopped during a non-resumable production step",
                    }
                )
            )
            self.record_event(
                workspace_id,
                artifact_id,
                stage="recovery",
                status="interrupted",
                message="Production was interrupted; retry is available",
                current=stopped.progress,
                total=100,
            )
            interrupted.append(artifact_id)
            self.release_lease(workspace_id, artifact_id)
        return {"resume": resume, "interrupted": interrupted}

    def asset_path(self, workspace_id: str, artifact_id: str, filename: str) -> Path:
        """Return a contained sidecar path for generated binary or text assets."""
        self._path(workspace_id, artifact_id)
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,120}", filename):
            raise ValueError("Invalid studio asset filename")
        directory = (self._directory(workspace_id) / artifact_id).resolve()
        if self.root not in directory.parents:
            raise ValueError("Studio asset path escapes storage root")
        directory.mkdir(parents=True, exist_ok=True)
        return directory / filename

    def _path(self, workspace_id: str, artifact_id: str) -> Path:
        if not re.fullmatch(r"artifact-[a-f0-9]{12}", artifact_id):
            raise ValueError("Invalid studio artifact id")
        return self._directory(workspace_id) / f"{artifact_id}.json"

    def _directory(self, workspace_id: str) -> Path:
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,80}", workspace_id):
            raise ValueError("Invalid workspace id")
        path = (self.root / workspace_id / "artifacts").resolve()
        if self.root not in path.parents:
            raise ValueError("Studio artifact path escapes storage root")
        return path


def _safe_event_details(value: dict[str, Any]) -> dict[str, Any]:
    blocked = ("secret", "token", "password", "api_key", "apikey", "authorization", "credential")

    def clean(item: Any, depth: int = 0) -> Any:
        if depth > 4:
            return "[truncated]"
        if isinstance(item, dict):
            return {
                str(key)[:80]: clean(child, depth + 1)
                for key, child in list(item.items())[:40]
                if not any(marker in str(key).casefold() for marker in blocked)
            }
        if isinstance(item, (list, tuple)):
            return [clean(child, depth + 1) for child in list(item)[:40]]
        if isinstance(item, str):
            return item[:500]
        if item is None or isinstance(item, (bool, int, float)):
            return item
        return str(item)[:500]

    return clean(value)


