_LEGACY_CARD_HEADING = re.compile(
    r"^#{2,4}\s+(?:فلش[\s\u200c-]*کارت|flash\s*card).*$",
    flags=re.IGNORECASE | re.MULTILINE,
)
_LEGACY_QUESTION_MARKER = r"^\s*[*+-]?\s*\*\*(?:پرسش|س[ؤو]ال|question|front)\s*:\*\*\s*"
_LEGACY_ANSWER_MARKER = r"^\s*[*+-]?\s*\*\*(?:پاسخ|answer|back)\s*:\*\*\s*"
_LEGACY_SOURCE_MARKER = r"^\s*[*+-]?\s*\*\*(?:ارجاع|منبع|source|citations?)\s*:\*\*\s*"


_GENERIC_DECK_SOURCE_SECTION = re.compile(
    r"^\s*(?:"
    r"abstract|introduction|background|methods?|materials?(?: and)? methods?|"
    r"methodology|results?|discussion|conclusions?|references?|bibliography|authors?|"
    r"acknowledg(?:e)?ments?|appendix|supplementary(?: material| information)?|"
    r"چکیده|مقدمه|پیش[‌-]?زمینه|روش(?:[‌-]?ها)?|مواد و روش[‌-]?ها|"
    r"نتایج|بحث|نتیجه[‌-]?گیری|منابع|نویسندگان|قدردانی|ضمیمه|پیوست"
    r")\s*$",
    flags=re.IGNORECASE,
)


def _plain_legacy_card_text(value: str) -> str:
    lines = []
    for raw_line in value.splitlines():
        line = re.sub(r"^\s*[*+-]\s*", "", raw_line).strip()
        line = line.replace("**", "").strip()
        if line:
            lines.append(line)
    return "\n".join(lines)


def parse_legacy_flashcards(markdown: str) -> list[dict[str, Any]]:
    """Recover cards from the Markdown format generated by PaperLens 1.x."""
    headings = list(_LEGACY_CARD_HEADING.finditer(markdown))
    cards = []
    for index, heading in enumerate(headings):
        end = headings[index + 1].start() if index + 1 < len(headings) else len(markdown)
        block = markdown[heading.end() : end]
        question = re.search(
            rf"{_LEGACY_QUESTION_MARKER}(.*?)(?={_LEGACY_ANSWER_MARKER})",
            block,
            flags=re.IGNORECASE | re.MULTILINE | re.DOTALL,
        )
        answer = re.search(
            rf"{_LEGACY_ANSWER_MARKER}(.*?)(?={_LEGACY_SOURCE_MARKER}|^\s*---|\Z)",
            block,
            flags=re.IGNORECASE | re.MULTILINE | re.DOTALL,
        )
        if not question or not answer:
            continue
        front = _plain_legacy_card_text(question.group(1))
        back = _plain_legacy_card_text(answer.group(1))
        if not front or not back:
            continue
        citations = list(dict.fromkeys(f"S{item}" for item in re.findall(r"\[S(\d+)\]", block)))
        cards.append({"front": front, "back": back, "citations": citations})
    return cards


