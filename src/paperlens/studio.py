    @staticmethod
    def _normalize_infographic(payload: dict[str, Any]) -> dict[str, Any]:
        sections = []
        for item in StudioService._list(payload, "sections", "items", "blocks"):
            if not isinstance(item, dict):
                raise ValueError("Every infographic section must be an object")
            heading = item.get("heading") or item.get("title")
            body = item.get("body") or item.get("text") or item.get("description")
            metric = item.get("metric")
            if isinstance(metric, dict):
                label = str(metric.get("label") or metric.get("name") or "").strip()
                value = str(metric.get("value") or metric.get("amount") or "").strip()
                metric = ": ".join(part for part in (label, value) if part)
            elif isinstance(metric, str) and len(metric) <= 1_000:
                # Some compatible models wrap a metric object in a Python-style string.
                # Recover the two display fields without exposing representation syntax.
                pairs = dict(
                    re.findall(
                        r"['\"](label|name|value|amount)['\"]\s*:\s*['\"]([^'\"]+)['\"]",
                        metric,
                        re.IGNORECASE,
                    )
                )
                if pairs:
                    label = str(pairs.get("label") or pairs.get("name") or "").strip()
                    value = str(pairs.get("value") or pairs.get("amount") or "").strip()
                    metric = ": ".join(part for part in (label, value) if part)
            if not str(heading or "").strip() or not str(body or metric or "").strip():
                raise ValueError("Every infographic section must have a heading and content")
            sections.append(
                {
                    "heading": str(heading).strip(),
                    "body": str(body or "").strip(),
                    "metric": str(metric).strip() if metric is not None else "",
                    "citations": StudioService._citations(item.get("citations")),
                }
            )
        return {**payload, "sections": sections}

    @staticmethod
    def _normalize_data_table(payload: dict[str, Any]) -> dict[str, Any]:
        columns = []
        for item in StudioService._list(payload, "columns", "headers"):
            label = (
                item
                if isinstance(item, str)
                else item.get("label")
                if isinstance(item, dict)
                else ""
            )
            if str(label).strip():
                columns.append(str(label).strip())
        if not columns:
            raise ValueError("Data table columns cannot be empty")
        rows = []
        for item in StudioService._list(payload, "rows", "records", "items"):
            if isinstance(item, list):
                rows.append(
                    {
                        column: item[index] if index < len(item) else ""
                        for index, column in enumerate(columns)
                    }
                )
            elif isinstance(item, dict):
                rows.append({column: item.get(column, "") for column in columns})
            else:
                raise ValueError("Every data-table row must be an object or list")
        return {**payload, "columns": columns, "rows": rows}

    def _repair_structured_output(
        self,
        artifact: StudioArtifact,
        context: str,
        result: GenerationResult,
        error: Exception,
    ) -> GenerationResult:
        return self._run_output(
            artifact,
            instructions=(
                self._instructions(artifact)
                + " The previous structured draft was invalid. Return a complete, non-empty "
                "JSON object only, using exactly the requested schema. Do not use Markdown "
                "fences or commentary. Escape every newline and control character inside "
                "strings, close every string and container, and keep descriptions concise "
                "enough to finish the object in this response."
            ),
            user_input=(
                f"Source evidence:\n{context}\n\n"
                f"Invalid draft:\n{result.text[:12_000]}\n\n"
                f"Validation problem: {type(error).__name__}: {str(error)[:300]}"
            ),
        )

    def _run_output(
        self,
        artifact: StudioArtifact,
        *,
        instructions: str,
        user_input: str,
    ) -> GenerationResult:
        validated_runner = getattr(self.language_model, "run_validated", None)
        if artifact.artifact_type in _STRUCTURED_TYPES and callable(validated_runner):

            def is_renderable(result: GenerationResult) -> bool:
                try:
                    data, markdown, title = self._decode_output(artifact, result.text)
                except (json.JSONDecodeError, ValueError):
                    return False
                visible = "\n".join(
                    (title, markdown, json.dumps(data, ensure_ascii=False, default=str))
                )
                return self._requested_language_matches(artifact, visible)

            bounded_runner = getattr(self.language_model, "run_validated_bounded", None)
            runner = bounded_runner if callable(bounded_runner) else validated_runner
            arguments: dict[str, Any] = {
                "instructions": instructions,
                "user_input": user_input,
                "validation_profile": f"studio:{artifact.artifact_type}",
            }
            if callable(bounded_runner) and runner is bounded_runner:
                arguments["max_attempts"] = 6
                arguments["max_credential_attempts"] = 6
                arguments["max_output_tokens"] = (
                    6_000 if artifact.artifact_type == "slide_deck" else 3_000
                )
            return runner(
                is_renderable,
                **arguments,
            )
        if callable(validated_runner):

            def is_complete(result: GenerationResult) -> bool:
                text = result.text.strip()
                return self._looks_complete(
                    text, result.finish_reason
                ) and self._requested_language_matches(artifact, text)

            return validated_runner(
                is_complete,
                instructions=instructions,
                user_input=user_input,
                validation_profile=f"studio:{artifact.artifact_type}",
                max_attempts=6,
                max_credential_attempts=6,
            )
        return self.language_model.run(instructions=instructions, user_input=user_input)

    @staticmethod
    def _requested_language_matches(artifact: StudioArtifact, text: str) -> bool:
        return artifact.language != "fa" or is_clean_persian(text)

    def _model_status(self) -> dict[str, Any]:
        status = getattr(self.language_model, "failover_status", None)
        if not callable(status):
            return {}
        value = status()
        return dict(value) if isinstance(value, dict) else {}

    def _complete_output(
        self,
        artifact: StudioArtifact,
        context: str,
        result: GenerationResult,
    ) -> GenerationResult:
        """Continue token-limited deliverables without silently saving a fragment."""
        if artifact.artifact_type in _STRUCTURED_TYPES:
            return result
        text = result.text.strip()
        if not text:
            raise ValueError("Studio output is empty")
        finish_reason = result.finish_reason
        for _ in range(2):
            if self._looks_complete(text, finish_reason):
                break
            continuation = self.language_model.run(
                instructions=(
                    self._instructions(artifact)
                    + " The draft below ended before completion. Continue exactly where it "
                    "stopped, finish every open section, and do not repeat earlier content."
                ),
                user_input=(
                    f"Source evidence:\n{context}\n\n"
                    f"Incomplete draft:\n{text}\n\n"
                    "Return only the missing continuation."
                ),
            )
            text = self._join_continuation(text, continuation.text)
            finish_reason = continuation.finish_reason
        if not self._looks_complete(text, finish_reason):
            raise ValueError("Studio output remained incomplete after continuation attempts")
        text = re.sub(r"\s*<!--\s*PAPERLENS_COMPLETE\s*-->\s*$", "", text).rstrip()
        return result.model_copy(update={"text": text, "finish_reason": finish_reason})

    @staticmethod
    def _looks_complete(text: str, finish_reason: str | None) -> bool:
        if (finish_reason or "").casefold() in {
            "length",
            "max_tokens",
            "max_output_tokens",
            "incomplete",
        }:
            return False
        stripped = text.rstrip()
        if not stripped:
            return False
        if stripped.count("```") % 2 or stripped.count("**") % 2:
            return False
        return bool(re.search(r"<!--\s*PAPERLENS_COMPLETE\s*-->\s*$", stripped, re.IGNORECASE))

    @staticmethod
    def _join_continuation(draft: str, continuation: str) -> str:
        addition = re.sub(
            r"^\s*(?:continuation|continued|ادامه)\s*:?\s*",
            "",
            continuation.strip(),
            flags=re.IGNORECASE,
        )
        if not addition:
            return draft.strip()
        maximum = min(len(draft), len(addition), 500)
        overlap = 0
        for size in range(maximum, 19, -1):
            if draft[-size:] == addition[:size]:
                overlap = size
                break
        touches_markup = draft.endswith((" ", "\n")) or addition.startswith((" ", "\n", "*"))
        separator = "" if touches_markup else " "
        missing = addition[overlap:].lstrip() if overlap else addition
        return f"{draft.rstrip()}{separator}{missing}".strip()

