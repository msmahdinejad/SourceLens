    @staticmethod
    def _decode_output(
        artifact: StudioArtifact,
        text: str,
    ) -> tuple[dict[str, Any], str, str | None]:
        clean = text.strip()
        if not clean:
            raise ValueError("Studio output is empty")
        if artifact.artifact_type not in _STRUCTURED_TYPES:
            return {}, clean, None
        try:
            payload = StudioService._json_object(clean)
        except (json.JSONDecodeError, ValueError):
            cards = parse_legacy_flashcards(clean) if artifact.artifact_type == "flashcards" else []
            if not cards:
                raise
            payload = {"title": artifact.title, "cards": cards}
        if not isinstance(payload, dict):
            raise ValueError("Structured studio output must be a JSON object")
        normalizer = {
            "quiz": StudioService._normalize_quiz,
            "chart": StudioService._normalize_chart,
            "timeline": StudioService._normalize_timeline,
            "concept_map": StudioService._normalize_concept_map,
            "flashcards": StudioService._normalize_flashcards,
            "infographic": StudioService._normalize_infographic,
            "data_table": StudioService._normalize_data_table,
            "slide_deck": StudioService._normalize_slide_deck,
            "video_overview": StudioService._normalize_video_overview,
        }[artifact.artifact_type]
        payload = normalizer(payload)
        if artifact.artifact_type == "video_overview":
            StudioService._validate_video_scene_language(artifact.language, payload)
        if artifact.artifact_type == "video_overview" and artifact.options.get(
            "_agent_video_plan"
        ):
            payload = StudioService._apply_video_agent_plan(
                payload,
                artifact.options["_agent_video_plan"],
            )
        if artifact.artifact_type == "slide_deck":
            slides = payload.get("slides") or []
            count = len(slides)
            if not 2 <= count <= 40:
                raise ValueError("Slide plans must contain between 2 and 40 substantive slides")
            requested = int(artifact.options.get("slide_count", 12))
            strategy = str(artifact.options.get("slide_count_strategy") or "auto")
            if strategy == "auto" and len(artifact.document_ids) >= 3:
                minimum = {
                    "concise": 2,
                    "standard": 4,
                    "deep": 5,
                    "auto": 4,
                }.get(str(artifact.options.get("content_depth") or "auto"), 4)
                if count < minimum:
                    raise ValueError(
                        "Automatic multi-source deck is too shallow for the requested "
                        f"content depth; expected at least {minimum} substantive slides, "
                        f"received {count}"
                    )
            if strategy == "auto" and count > 18:
                raise ValueError(
                    f"Automatic decks must stay concise; received {count} substantive slides"
                )
            if strategy == "fixed" and count != requested:
                raise ValueError(
                    f"Fixed slide count requires {requested} substantive slides; received {count}"
                )
            if strategy == "maximum" and count > requested:
                raise ValueError(
                    f"Maximum slide count is {requested}; received {count} substantive slides"
                )
            image_strategy = str(artifact.options.get("image_strategy") or "auto")
            media_density = str(artifact.options.get("media_density") or "auto")
            if image_strategy not in {"none", "diagrams_only"} and media_density != "minimal":
                media_slides = sum(bool(slide.get("image_queries")) for slide in slides)
                native_visual_layouts = {
                    "chart_focus",
                    "dashboard",
                    "metrics_dashboard",
                    "process_flow",
                    "timeline_story",
                    "comparison_dual",
                    "matrix_2x2",
                    "table_clean",
                    "funnel",
                }
                visual_slides = sum(
                    bool(slide.get("image_queries"))
                    or bool(slide.get("chart"))
                    or bool(slide.get("equation"))
                    or bool(slide.get("rows"))
                    or (
                        str(slide.get("layout") or "") in native_visual_layouts
                        and bool(
                            slide.get("items")
                            or slide.get("left_items")
                            or slide.get("right_items")
                        )
                    )
                    for slide in slides
                )
                minimum_media = {
                    "rich": max(1, (count * 3 + 4) // 5),
                    "balanced": max(1, (count * 2 + 4) // 5),
                    "auto": max(1, (count + 3) // 4),
                }.get(media_density, max(1, (count + 3) // 4))
                minimum_queries = max(1, (count + 3) // 4)
                if media_slides < minimum_queries or visual_slides < minimum_media:
                    raise ValueError(
                        "The deck needs concrete licensed-media queries on at least "
                        f"{minimum_queries} slide(s) and evidence visuals on at least "
                        f"{minimum_media}; received {media_slides} and {visual_slides}"
                    )
        if artifact.artifact_type == "video_overview":
            scenes = payload.get("scenes") or []
            count = len(scenes)
            if not 1 <= count <= 40:
                raise ValueError("Video plans must contain between 1 and 40 substantive scenes")
            requested = int(artifact.options.get("scene_count", 8))
            strategy = str(artifact.options.get("scene_count_strategy") or "auto")
            agent_count = artifact.options.get("_agent_scene_count")
            if isinstance(agent_count, int) and count != agent_count:
                raise ValueError(
                    "Autonomous planner selected "
                    f"{agent_count} substantive scenes; received {count}"
                )
            if agent_count is None and strategy == "fixed" and count != requested:
                raise ValueError(
                    f"Fixed scene count requires {requested} substantive scenes; received {count}"
                )
            if agent_count is None and strategy == "maximum" and count > requested:
                raise ValueError(
                    f"Maximum scene count is {requested}; received {count} substantive scenes"
                )
            if "duration_seconds" in artifact.options:
                requested_duration = int(artifact.options["duration_seconds"])
                planned_duration = round(
                    sum(float(scene.get("duration_seconds") or 0) for scene in scenes)
                )
                if planned_duration != requested_duration:
                    raise ValueError(
                        "Video scene timing must total exactly "
                        f"{requested_duration} seconds; received {planned_duration}"
                    )
        title = str(payload.get("title") or artifact.title)
        return payload, "", title

    @staticmethod
    def _json_object(text: str) -> dict[str, Any]:
        """Extract one complete object while tolerating common model JSON wrappers."""
        decoder = json.JSONDecoder(strict=False)
        last_error: json.JSONDecodeError | None = None
        for match in re.finditer(r"\{", text):
            try:
                payload, _ = decoder.raw_decode(text, match.start())
            except json.JSONDecodeError as error:
                last_error = error
                continue
            if isinstance(payload, dict):
                return payload
        if last_error is not None:
            raise last_error
        raise ValueError("Structured studio output must contain a JSON object")

    @staticmethod
    def _apply_video_agent_plan(
        payload: dict[str, Any],
        plan: dict[str, Any],
    ) -> dict[str, Any]:
        scenes = payload.get("scenes") if isinstance(payload.get("scenes"), list) else []
        planned = plan.get("scenes") if isinstance(plan.get("scenes"), list) else []
        if len(scenes) != len(planned):
            raise ValueError(
                f"Agentic video plan requires {len(planned)} scenes; received {len(scenes)}"
            )
        grounded_scenes = []
        total_narration_words = 0
        total_narration_budget = sum(
            int(scene.get("narration_word_budget") or 1)
            for scene in planned
            if isinstance(scene, dict)
        )
        for index, (scene, contract) in enumerate(zip(scenes, planned, strict=True), start=1):
            if not isinstance(scene, dict) or not isinstance(contract, dict):
                raise ValueError("Every agentic video scene must be an object")
            media_request = (
                contract.get("media_request")
                if isinstance(contract.get("media_request"), dict)
                else None
            )
            if media_request is None:
                queries: list[str] = []
            else:
                raw_queries = scene.get("media_queries")
                candidates = raw_queries if isinstance(raw_queries, list) else []
                # The evidence-derived request can be a long quoted passage. Prefer the
                # model's concise, scene-specific search phrases and retain the grounded
                # request as a last-resort fallback.
                candidates = [*candidates, scene.get("media_query"), media_request.get("query")]
                queries = list(
                    dict.fromkeys(
                        re.sub(r"\bS\d+\b", "", str(value), flags=re.I).strip(
                            " []:;,-"
                        )
                        for value in candidates
                        if str(value or "").strip()
                    )
                )
                queries = [
                    query
                    for query in queries
                    if query and not re.search(r"https?://", query, flags=re.I)
                ][:4]
                if not queries:
                    raise ValueError(f"Scene {index} requires a source-derived media query")
            chart = contract.get("chart") if isinstance(contract.get("chart"), dict) else {}
            narration = str(scene.get("narration") or "").strip()
            narration_budget = int(contract.get("narration_word_budget") or 1)
            total_narration_words += len(narration.split())
            visual = scene.get("visual") if isinstance(scene.get("visual"), dict) else {}
            visual = {
                **visual,
                "intent": str(contract.get("visual_intent") or "footage"),
                "chart": chart or None,
            }
            grounded_scenes.append(
                {
                    **scene,
                    "id": str(contract.get("id") or f"scene-{index}"),
                    "phase": str(contract.get("phase") or "development"),
                    "role": str(contract.get("role") or "insight"),
                    "objective": str(contract.get("objective") or ""),
                    "duration_seconds": int(contract.get("duration_seconds") or 1),
                    "narration_word_budget": narration_budget,
                    "visual_intent": str(contract.get("visual_intent") or "footage"),
                    "evidence_ids": list(contract.get("evidence_ids") or []),
                    "citations": list(contract.get("citations") or []),
                    "chart": chart,
                    "visual": visual,
                    "media_query": queries[0] if queries else "",
                    "media_queries": queries,
                    "media_required": media_request is not None,
                    "media_provenance": media_request or {},
                }
            )
        is_persian_narration = any(
            re.search(r"[\u0600-\u06ff]", str(scene.get("narration") or ""))
            for scene in grounded_scenes
        )
        # Persian tokenization needs more room than English, but an overly generous
        # margin lets a nominal 60-second script run long at natural TTS speed.
        speech_margin = 1.85 if is_persian_narration else 1.25
        allowed_narration_words = max(
            total_narration_budget + 5,
            round(total_narration_budget * speech_margin),
        )
        if total_narration_words > allowed_narration_words:
            raise ValueError(
                "Video narration exceeds its grounded total word budget of "
                f"{total_narration_budget} words (received {total_narration_words}; "
                f"maximum {allowed_narration_words})"
            )
        return {
            **payload,
            "narrative_arc": str(plan.get("narrative_arc") or ""),
            "pace": str(plan.get("pace") or "balanced"),
            "duration_seconds": int(plan.get("total_duration_seconds") or 30),
            "scenes": grounded_scenes,
        }

    @staticmethod
    def _list(payload: dict[str, Any], *names: str) -> list[Any]:
        for name in names:
            value = payload.get(name)
            if isinstance(value, list) and value:
                return value
        raise ValueError(f"Structured output must contain non-empty {names[0]}")

    @staticmethod
    def _citations(value: Any) -> list[str]:
        if not isinstance(value, list):
            return []
        return [str(item).strip() for item in value if str(item).strip()]

    @staticmethod
    def _normalize_flashcards(payload: dict[str, Any]) -> dict[str, Any]:
        raw_cards = payload.get("cards") or payload.get("flashcards") or payload.get("items")
        if not isinstance(raw_cards, list) or not raw_cards:
            raise ValueError("Flashcard output must contain at least one card")
        cards = []
        for item in raw_cards:
            if not isinstance(item, dict):
                raise ValueError("Every flashcard must be an object")
            front = item.get("front") or item.get("question") or item.get("term")
            back = item.get("back") or item.get("answer") or item.get("definition")
            if not str(front or "").strip() or not str(back or "").strip():
                raise ValueError("Every flashcard must have a front and back")
            citations = item.get("citations")
            cards.append(
                {
                    "front": str(front).strip(),
                    "back": str(back).strip(),
                    "citations": StudioService._citations(citations),
                }
            )
        return {**payload, "cards": cards}

    @staticmethod
    def _normalize_quiz(payload: dict[str, Any]) -> dict[str, Any]:
        questions = []
        for item in StudioService._list(payload, "questions", "items"):
            if not isinstance(item, dict):
                raise ValueError("Every quiz question must be an object")
            question = item.get("question") or item.get("prompt")
            choices = item.get("choices") or item.get("options")
            if not str(question or "").strip() or not isinstance(choices, list):
                raise ValueError("Every quiz question must have text and choices")
            normalized_choices = [str(choice).strip() for choice in choices if str(choice).strip()]
            if len(normalized_choices) < 2:
                raise ValueError("Every quiz question must have at least two choices")
            correct_index = item.get("correct_index")
            if not isinstance(correct_index, int) or isinstance(correct_index, bool):
                correct_answer = str(item.get("correct_answer") or "").strip()
                if correct_answer not in normalized_choices:
                    raise ValueError("Every quiz question must identify a correct choice")
                correct_index = normalized_choices.index(correct_answer)
            if not 0 <= correct_index < len(normalized_choices):
                raise ValueError("Quiz correct_index is outside the choices")
            questions.append(
                {
                    "question": str(question).strip(),
                    "choices": normalized_choices,
                    "correct_index": correct_index,
                    "explanation": str(item.get("explanation") or "").strip(),
                    "citations": StudioService._citations(item.get("citations")),
                }
            )
        return {**payload, "questions": questions}

    @staticmethod
    def _normalize_chart(payload: dict[str, Any]) -> dict[str, Any]:
        labels = [
            str(label).strip()
            for label in StudioService._list(payload, "labels", "categories")
            if str(label).strip()
        ]
        if not labels:
            raise ValueError("Chart labels cannot be empty")
        datasets = []
        for item in StudioService._list(payload, "datasets", "series"):
            if not isinstance(item, dict):
                raise ValueError("Every chart dataset must be an object")
            values = item.get("data") if isinstance(item.get("data"), list) else item.get("values")
            if not isinstance(values, list) or len(values) != len(labels):
                raise ValueError("Chart data must align with labels")
            if any(
                not isinstance(value, (int, float)) or isinstance(value, bool) for value in values
            ):
                raise ValueError("Chart values must be numeric")
            datasets.append(
                {
                    "label": str(item.get("label") or item.get("name") or "Series").strip(),
                    "data": values,
                }
            )
        chart_type = str(payload.get("chart_type") or "bar").casefold()
        if chart_type not in {"bar", "line", "pie", "scatter"}:
            chart_type = "bar"
        return {**payload, "chart_type": chart_type, "labels": labels, "datasets": datasets}

    @staticmethod
    def _normalize_slide_deck(payload: dict[str, Any]) -> dict[str, Any]:
        allowed_layouts = {
            "cover_cinematic",
            "editorial_split",
            "cards_icon",
            "metrics_dashboard",
            "timeline_story",
            "comparison_dual",
            "chart_focus",
            "matrix_2x2",
            "process_flow",
            "photo_mosaic",
            "quote_photo",
            "big_statement",
            "case_study",
            "table_clean",
            "funnel",
            "dashboard",
            "closing_actions",
        }
        legacy_layouts = {
            "cover": "cover_cinematic",
            "section": "big_statement",
            "key_points": "cards_icon",
            "metrics": "metrics_dashboard",
            "chart": "chart_focus",
            "comparison": "comparison_dual",
            "timeline": "timeline_story",
            "process": "process_flow",
            "quote": "quote_photo",
            "image_focus": "editorial_split",
            "closing": "closing_actions",
        }
        placeholder_titles = {
            "context",
            "evidence",
            "decision",
            "action",
            "current approach",
            "constraint",
            "risk",
            "improved approach",
            "opportunity",
            "outcome",
        }
        production_copy = re.compile(
            r"(?:"
            r"establish (?:the )?(?:subject|topic)|connect (?:the )?(?:strongest )?evidence|"
            r"interpret (?:the )?(?:documented )?(?:numeric )?result|"
            r"translate evidence|turn evidence into|clarif(?:y|ies) the (?:deck|presentation)|"
            r"موضوع و وعده (?:اصلی )?ارائه را روشن|"
            r"بین شواهد و معنای عملی|نتیجه عددی مستند را تفسیر|"
            r"شواهد را به اقدام|مهم.?ترین شواهد را به (?:یک )?نتیجه"
            r")",
            flags=re.I,
        )
        metadata_heading = re.compile(
            r"^(?:authors?|references?|bibliography|topics?|front matter|"
            r"data availability(?: statement)?|making sure you(?:'| a)re not a bot|"
            r"نویسندگان|منابع|ارجاعات|کتابنامه|موضوعات)$",
            flags=re.I,
        )

        def assert_audience_copy(value: Any, *, field: str) -> None:
            raw = str(value or "").strip()
            if not raw:
                return
            if production_copy.search(raw):
                raise ValueError(f"Internal production guidance leaked into slide {field}")
            if field == "title" and (
                metadata_heading.fullmatch(raw)
                or "http://" in raw.casefold()
                or "https://" in raw.casefold()
                or re.search(r"\[[^\]]+\]\([^)]*\)", raw)
                or re.fullmatch(r"[A-Z][\w'-]+,?\s+[A-Z](?:\.|$).{0,30}", raw)
            ):
                raise ValueError(f"Document metadata cannot become a slide {field}")

        def visible_text(value: Any) -> str:
            text = str(value or "").strip()
            text = re.sub(r"\[(?:S\d+)(?:\s*[,;]\s*S\d+)*\]", "", text, flags=re.I)
            return re.sub(r"\s{2,}", " ", text).strip()

        def looks_like_equation(value: str) -> bool:
            return bool(
                value
                and re.search(r"[=≈≤≥∑∫√→]", value)
                and re.search(r"[A-Za-zΑ-ω]\s*(?:\([^)]*\)|[_^]?[A-Za-z0-9])", value)
            )

        def items(value: Any) -> list[dict[str, str]]:
            normalized_items = []
            for position, item in enumerate(value if isinstance(value, list) else [], start=1):
                if isinstance(item, str):
                    item = {"title": item}
                if not isinstance(item, dict):
                    continue
                title = visible_text(item.get("title") or item.get("label"))
                body = visible_text(item.get("body") or item.get("description"))
                value = visible_text(item.get("value"))
                if not title:
                    raise ValueError(f"Slide item {position} must have a meaningful title")
                if title.casefold() in placeholder_titles or re.fullmatch(
                    r"point\s+\d+", title, flags=re.I
                ):
                    raise ValueError(f"Production placeholder is not allowed: {title}")
                normalized_items.append(
                    {
                        "icon": str(item.get("icon") or "sparkles").strip(),
                        "value": value,
                        "title": title,
                        "body": body,
                        "tone": str(item.get("tone") or "").strip(),
                    }
                )
            return normalized_items[:6]

        slides = []
        raw_slides = StudioService._list(payload, "slides", "pages")
        for index, item in enumerate(raw_slides, start=1):
            if not isinstance(item, dict):
                raise ValueError("Every slide must be an object")
            assert_audience_copy(item.get("title"), field="title")
            for field in ("subtitle", "body", "callout", "quote"):
                assert_audience_copy(item.get(field), field=field)
            title = visible_text(item.get("title"))
            if not title:
                raise ValueError("Every slide must have a title")
            raw_bullets = item.get("bullets") or item.get("points") or []
            bullets = (
                [str(value).strip() for value in raw_bullets if str(value).strip()]
                if isinstance(raw_bullets, list)
                else []
            )
            metrics = []
            for metric in item.get("metrics") or []:
                if isinstance(metric, dict):
                    metrics.append(
                        {
                            "value": str(metric.get("value") or "").strip(),
                            "label": str(metric.get("label") or "").strip(),
                        }
                    )
            chart = item.get("chart") if isinstance(item.get("chart"), dict) else {}
            if chart:
                if bool(chart.get("illustrative", False)):
                    raise ValueError("Illustrative or fabricated charts are not allowed")
                labels = chart.get("labels") if isinstance(chart.get("labels"), list) else []
                values = chart.get("values") if isinstance(chart.get("values"), list) else []
                raw_series_value = chart.get("series") or chart.get("datasets")
                raw_series = raw_series_value if isinstance(raw_series_value, list) else []
                series = []
                for position, entry in enumerate(raw_series[:3], start=1):
                    if not isinstance(entry, dict):
                        continue
                    entry_values = entry.get("values") or entry.get("data")
                    if not isinstance(entry_values, list):
                        continue
                    numeric = [
                        float(value)
                        for value in entry_values
                        if isinstance(value, (int, float)) and not isinstance(value, bool)
                    ]
                    if len(numeric) == len(labels) and len(labels) >= 2:
                        series.append(
                            {
                                "name": str(
                                    entry.get("name")
                                    or entry.get("label")
                                    or f"Series {position}"
                                ).strip(),
                                "values": numeric,
                            }
                        )
                numeric_values = [
                    float(value)
                    for value in values
                    if isinstance(value, (int, float)) and not isinstance(value, bool)
                ]
                if not series and len(numeric_values) == len(labels) and len(labels) >= 2:
                    series = [
                        {
                            "name": str(chart.get("label") or "Value").strip(),
                            "values": numeric_values,
                        }
                    ]
                chart = {
                    "type": (
                        str(chart.get("type") or "bar").casefold()
                        if str(chart.get("type") or "bar").casefold()
                        in {"bar", "line", "doughnut", "area", "column", "pie"}
                        else "bar"
                    ),
                    "title": str(chart.get("title") or "").strip(),
                    "labels": [str(value).strip() for value in labels],
                    "values": numeric_values,
                    "label": str(chart.get("label") or "").strip(),
                    "series": series,
                    "citations": StudioService._citations(chart.get("citations")),
                    "unit": visible_text(chart.get("unit")),
                    "method": visible_text(chart.get("method")),
                    "illustrative": False,
                }
                if (
                    not chart["labels"]
                    or not all(chart["labels"])
                    or len(chart["labels"]) < 2
                    or not chart["series"]
                ):
                    chart = {}
            layout = str(item.get("layout") or "cards_icon").casefold()
            layout = legacy_layouts.get(layout, layout)
            if layout not in allowed_layouts:
                layout = "cards_icon"
            image_queries = item.get("image_queries") or item.get("imageQueries") or []
            if not isinstance(image_queries, list):
                image_queries = []
            image_query = str(item.get("image_query") or item.get("imageQuery") or "").strip()
            rows = []
            for row in item.get("rows") or []:
                if isinstance(row, dict):
                    normalized_row = {
                        str(key).strip(): str(value or "").strip() for key, value in row.items()
                    }
                    if any(normalized_row.values()):
                        rows.append(normalized_row)
            image_queries = list(
                dict.fromkeys(
                    [
                        re.sub(r"\bS\d+\b", "", str(value), flags=re.I).strip(" []:;,-")
                        for value in [*image_queries, image_query]
                        if str(value).strip()
                    ]
                )
            )[:3]
            image_queries = [
                query
                for query in image_queries
                if len(re.findall(r"[A-Za-z][A-Za-z-]+", query)) >= 2
            ]
            photo_minimums = {
                "cover_cinematic": 1,
                "editorial_split": 1,
                "photo_mosaic": 3,
                "quote_photo": 1,
                "case_study": 2,
            }
            if layout in photo_minimums and not image_queries:
                query_words = re.findall(
                    r"[A-Za-z][A-Za-z0-9-]*",
                    " ".join(
                        [
                            title,
                            visible_text(item.get("subtitle")),
                            visible_text(item.get("body")),
                        ]
                    ),
                )
                if len(query_words) >= 4:
                    image_queries = [" ".join(query_words[:16])]
            slide_citations = StudioService._citations(item.get("citations"))
            if chart and not (slide_citations or chart.get("citations")):
                raise ValueError("Every chart must cite the source labels for its numeric data")
            footnote = visible_text(item.get("footnote"))
            equation = visible_text(item.get("equation"))
            if not equation and looks_like_equation(footnote):
                equation = footnote
                footnote = ""
            visual_hierarchy = str(
                item.get("visual_hierarchy") or item.get("visualHierarchy") or ""
            ).strip().casefold()
            if visual_hierarchy not in {"title", "equation", "visual", "content", "balanced"}:
                visual_hierarchy = "equation" if equation else "balanced"
            if equation:
                visual_hierarchy = "equation"
            spacing = str(item.get("spacing") or "balanced").strip().casefold()
            if spacing not in {"compact", "balanced", "airy"}:
                spacing = "balanced"
            slides.append(
                {
                    "id": str(item.get("id") or f"slide-{index}"),
                    "layout": layout,
                    "mode": (
                        str(item.get("mode") or "light").casefold()
                        if str(item.get("mode") or "light").casefold()
                        in {"light", "dark", "accent", "photo"}
                        else "light"
                    ),
                    "kicker": str(item.get("kicker") or "").strip(),
                    "title": title,
                    "subtitle": visible_text(item.get("subtitle")),
                    "body": visible_text(item.get("body")),
                    "bullets": bullets[:8],
                    "metrics": metrics[:6],
                    "chart": chart,
                    "rows": rows[:8],
                    "quote": visible_text(item.get("quote")),
                    "quote_source": str(
                        item.get("quote_source") or item.get("quoteSource") or ""
                    ).strip(),
                    "callout": visible_text(item.get("callout")),
                    "footnote": footnote,
                    "equation": equation,
                    "equation_label": visible_text(
                        item.get("equation_label") or item.get("equationLabel")
                    ),
                    "visual_hierarchy": visual_hierarchy,
                    "spacing": spacing,
                    "image_query": image_queries[0] if image_queries else "",
                    "image_queries": image_queries,
                    "focal_point": str(
                        item.get("focal_point") or item.get("focalPoint") or "center"
                    ).casefold(),
                    "items": items(item.get("items")),
                    "left_title": str(
                        item.get("left_title") or item.get("leftTitle") or ""
                    ).strip(),
                    "right_title": str(
                        item.get("right_title") or item.get("rightTitle") or ""
                    ).strip(),
                    "left_items": items(item.get("left_items") or item.get("leftItems")),
                    "right_items": items(item.get("right_items") or item.get("rightItems")),
                    "x_axis_label": visible_text(
                        item.get("x_axis_label") or item.get("xAxisLabel")
                    ),
                    "y_axis_label": visible_text(
                        item.get("y_axis_label") or item.get("yAxisLabel")
                    ),
                    "speaker_notes": str(
                        item.get("speaker_notes") or item.get("speakerNotes") or ""
                    ).strip(),
                    "citations": slide_citations,
                    "media_required": bool(
                        item.get("media_required") or item.get("mediaRequired")
                    ),
                }
            )
            slide = slides[-1]
            needed_media = photo_minimums.get(layout, 0)
            if needed_media and len(image_queries) < needed_media:
                if image_queries:
                    layout = "editorial_split"
                    needed_media = 1
                else:
                    layout = "cards_icon" if len(slide["items"]) >= 2 else "big_statement"
                    needed_media = 0
                slide["layout"] = layout
            slide["media_required"] = bool(needed_media or slide["media_required"])
            body_required_layouts = {
                "cards_icon",
                "process_flow",
                "timeline_story",
                "matrix_2x2",
                "comparison_dual",
                "case_study",
                "table_clean",
                "closing_actions",
                "editorial_split",
            }
            layout_items = [*slide["items"], *slide["left_items"], *slide["right_items"]]
            if layout in body_required_layouts and any(not entry["body"] for entry in layout_items):
                raise ValueError(f"Every {layout} item must include substantive explanatory text")
            if layout == "closing_actions" and len(slide["items"]) < 2:
                layout = "big_statement"
                slide["layout"] = layout
            if layout == "comparison_dual" and (
                not slide["left_items"] or not slide["right_items"]
            ):
                layout = "cards_icon" if len(slide["items"]) >= 2 else "big_statement"
                slide["layout"] = layout
            if layout == "matrix_2x2" and (
                len(slide["items"]) != 4
                or not slide["x_axis_label"]
                or not slide["y_axis_label"]
            ):
                layout = "cards_icon" if len(slide["items"]) >= 2 else "big_statement"
                slide["layout"] = layout
            if layout in {"chart_focus", "dashboard"} and not slide["chart"]:
                layout = "cards_icon" if len(slide["items"]) >= 2 else "big_statement"
                slide["layout"] = layout
            if layout == "table_clean" and any(not entry["value"] for entry in slide["items"]):
                layout = "cards_icon" if len(slide["items"]) >= 2 else "big_statement"
                slide["layout"] = layout
            meaningful = any(
                [
                    slide["subtitle"],
                    slide["body"],
                    slide["bullets"],
                    slide["metrics"],
                    slide["rows"],
                    slide["quote"],
                    slide["callout"],
                    slide["chart"],
                    slide["items"],
                    slide["left_items"],
                    slide["right_items"],
                    slide["image_queries"],
                    slide["equation"],
                ]
            )
            if not meaningful:
                raise ValueError(f"Slide {index} contains only a title and no substantive content")
            chart_detail: list[str] = []
            if slide["chart"]:
                chart_detail.extend(
                    str(value or "")
                    for value in (
                        slide["chart"].get("title"),
                        slide["chart"].get("label"),
                        slide["chart"].get("unit"),
                        slide["chart"].get("method"),
                        *slide["chart"].get("labels", []),
                    )
                )
                for series in slide["chart"].get("series", []):
                    chart_detail.append(str(series.get("name") or ""))
                    chart_detail.extend(str(value) for value in series.get("values", []))
            visible_detail = " ".join(
                str(value or "")
                for value in (
                    slide["subtitle"],
                    slide["body"],
                    slide["quote"],
                    slide["callout"],
                    slide["equation"],
                    *slide["bullets"],
                    *(
                        metric["value"] + " " + metric["label"]
                        for metric in slide["metrics"]
                    ),
                    *(" ".join(row.values()) for row in slide["rows"]),
                    *chart_detail,
                    *(entry["title"] + " " + entry["body"] for entry in layout_items),
                )
            ).strip()
            if index > 1 and len(re.sub(r"\s+", "", visible_detail)) < 20:
                raise ValueError(f"Slide {index} does not contain enough audience-facing content")
        if not slides:
            raise ValueError("A slide deck must contain at least one slide")
        return {
            **payload,
            "title": str(payload.get("title") or slides[0]["title"]).strip(),
            "subtitle": str(payload.get("subtitle") or "").strip(),
            "narrative": str(payload.get("narrative") or "").strip(),
            "theme": payload.get("theme") if isinstance(payload.get("theme"), dict) else {},
            "direction": (
                payload.get("direction") if isinstance(payload.get("direction"), dict) else {}
            ),
            "slides": slides,
        }

