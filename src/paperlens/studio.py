    @staticmethod
    def _validate_video_scene_language(language: str, payload: dict[str, Any]) -> None:
        """Reject source boilerplate or wrong-language copy before it reaches the renderer."""
        boilerplate = re.compile(
            r"https?://|www\.|for details see|\b(?:references?|publication|doi)\b",
            re.IGNORECASE,
        )
        for index, scene in enumerate(payload.get("scenes") or [], start=1):
            if not isinstance(scene, dict):
                continue
            for field in ("title", "kicker", "on_screen_text", "narration"):
                value = str(scene.get(field) or "").strip()
                if not value:
                    continue
                if boilerplate.search(value):
                    raise ValueError(
                        f"Scene {index} {field} contains source or reference boilerplate"
                    )
                persian = len(re.findall(r"[\u0600-\u06ff]", value))
                latin = len(re.findall(r"[A-Za-z]", value))
                if language == "fa" and (
                    persian < (8 if field == "narration" else 2) or latin > persian
                ):
                    raise ValueError(f"Scene {index} {field} is not clean Persian")
                if language == "en" and persian > max(2, latin // 5):
                    raise ValueError(f"Scene {index} {field} is not clean English")

    @staticmethod
    def _narration_signature(value: str) -> str:
        return re.sub(r"[^\w]+", " ", value.casefold(), flags=re.UNICODE).strip()

    @staticmethod
    def _normalize_concept_map(payload: dict[str, Any]) -> dict[str, Any]:
        nodes = []
        for index, item in enumerate(StudioService._list(payload, "nodes", "concepts"), start=1):
            if isinstance(item, str):
                item = {"label": item}
            if not isinstance(item, dict) or not str(item.get("label") or "").strip():
                raise ValueError("Every mind-map node must have a label")
            nodes.append(
                {
                    "id": str(item.get("id") or f"n{index}"),
                    "label": str(item["label"]).strip(),
                    "description": str(item.get("description") or "").strip(),
                    "citations": StudioService._citations(item.get("citations")),
                }
            )
        edges = []
        raw_edges = payload.get("edges") or payload.get("relationships") or []
        if not isinstance(raw_edges, list):
            raise ValueError("Mind-map edges must be a list")
        for item in raw_edges:
            if not isinstance(item, dict) or not item.get("source") or not item.get("target"):
                continue
            edges.append(
                {
                    "source": str(item["source"]),
                    "target": str(item["target"]),
                    "label": str(item.get("label") or item.get("relationship") or "related"),
                }
            )
        if not nodes:
            raise ValueError("A concept map must contain at least one node")
        raw_root = payload.get("root")
        if isinstance(raw_root, dict):
            root_id = str(raw_root.get("id") or "root").strip() or "root"
            if not any(node["id"] == root_id for node in nodes):
                root_label = str(raw_root.get("label") or payload.get("title") or "").strip()
                if not root_label:
                    raise ValueError("A concept-map root object must have a label")
                nodes.insert(
                    0,
                    {
                        "id": root_id,
                        "label": root_label,
                        "description": str(raw_root.get("description") or "").strip(),
                        "citations": StudioService._citations(raw_root.get("citations")),
                    },
                )
            root = root_id
        else:
            root = str(raw_root or payload.get("title") or nodes[0]["id"]).strip()
        return {
            **payload,
            "root": root,
            "nodes": nodes,
            "edges": edges,
        }

