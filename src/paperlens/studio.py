_WORKFLOW_REGISTRY: WorkflowRegistry | None = None


def studio_workflow_registry() -> WorkflowRegistry:
    global _WORKFLOW_REGISTRY
    if _WORKFLOW_REGISTRY is not None:
        return _WORKFLOW_REGISTRY

    from paperlens.podcast import normalize_podcast_options, podcast_catalog_item

    registry = WorkflowRegistry()
    podcast = podcast_catalog_item()
    registry.register(
        "audio_overview",
        fields=podcast["fields"],
        retrieval_focus=_RETRIEVAL_FOCUS["audio_overview"],
        guidance="Create the requested source-grounded audio overview.",
        creatable=True,
        normalizer=normalize_podcast_options,
    )
    ordered_types = (*_CREATION_TYPES, *(_RETRIEVAL_FOCUS.keys() - _CREATION_TYPES))
    for artifact_type in ordered_types:
        if artifact_type == "audio_overview":
            continue
        creatable = artifact_type in _CREATION_TYPES
        fields = (
            {**_COMMON_OPTION_SCHEMA, **_CREATION_OPTION_SCHEMA[artifact_type]}
            if creatable
            else {}
        )
        registry.register(
            artifact_type,
            fields=fields,
            retrieval_focus=_RETRIEVAL_FOCUS[artifact_type],
            guidance=_TYPE_GUIDANCE[artifact_type],
            creatable=creatable,
            typed_options=creatable,
        )
    _WORKFLOW_REGISTRY = registry
    return registry


def studio_creation_catalog() -> list[dict[str, Any]]:
    return studio_workflow_registry().catalog()


def normalize_studio_options(artifact_type: StudioArtifactType, options: dict[str, Any]) -> dict:
    registry = studio_workflow_registry()
    return (
        registry.normalize(artifact_type, options)
        if registry.contains(artifact_type)
        else dict(options)
    )


class StudioService:
    """Generate source-scoped research deliverables through the shared LLM pool."""

    def __init__(
        self,
        *,
        workspaces: WorkspaceStore,
        knowledge_base: StudioKnowledgeBase,
        language_model: LanguageModel,
        artifacts: StudioArtifactStore,
    ) -> None:
        self.workspaces = workspaces
        self.knowledge_base = knowledge_base
        self.language_model = language_model
        self.artifacts = artifacts

    def create(self, request: StudioGenerationRequest) -> StudioArtifact:
        workspace = self.workspaces.get(request.workspace_id)
        selected_ids = list(dict.fromkeys(request.document_ids))
        documents = {item.document_id: item for item in workspace.documents}
        unknown = [item for item in selected_ids if item not in documents]
        if unknown:
            raise ValueError(f"Unknown selected document: {unknown[0]}")
        unavailable = [item for item in selected_ids if documents[item].status != "ready"]
        if unavailable:
            raise ValueError(f"Selected document is not ready: {unavailable[0]}")
        title = request.title or self._default_title(request.artifact_type)
        options = normalize_studio_options(request.artifact_type, request.options)
        artifact = self.artifacts.save(
            StudioArtifact(
                artifact_id=f"artifact-{uuid4().hex[:12]}",
                workspace_id=request.workspace_id,
                artifact_type=request.artifact_type,
                title=title,
                title_is_custom=request.title is not None,
                document_ids=selected_ids,
                language=request.language,
                options=options,
            )
        )
        self.artifacts.record_event(
            artifact.workspace_id,
            artifact.artifact_id,
            stage="queue",
            status="queued",
            message="Studio job queued",
            current=0,
            total=1,
            details={"artifact_type": artifact.artifact_type},
        )
        return artifact

    def generate(self, artifact_id: str, *, workspace_id: str | None = None) -> StudioArtifact:
        artifact = self._find(artifact_id, workspace_id)
        cancelled = self._cancelled_artifact(artifact)
        if cancelled is not None:
            return cancelled
        artifact = self.artifacts.save(
            artifact.model_copy(
                update={"status": "gathering", "stage": "source_selection", "progress": 5}
            )
        )
        self.artifacts.record_event(
            artifact.workspace_id,
            artifact.artifact_id,
            stage="source_selection",
            status="running",
            message="Selected source scope validated",
            current=len(artifact.document_ids),
            total=len(artifact.document_ids),
        )
        attempt_id: int | None = None
        try:
            per_document = {
                "focused": 3,
                "balanced": 5,
                "comprehensive": 8,
            }.get(str(artifact.options.get("evidence_depth")), 5)
            query = self._retrieval_query(artifact)
            if artifact.artifact_type in {"slide_deck", "video_overview"} and callable(
                global_search := getattr(self.knowledge_base, "search", None)
            ):
                evidence_limit = {
                    "focused": 12,
                    "balanced": 18,
                    "comprehensive": 24,
                }.get(str(artifact.options.get("evidence_depth")), 18)
                evidence = global_search(
                    artifact.workspace_id,
                    query,
                    top_k=evidence_limit,
                    document_ids=set(artifact.document_ids),
                )
            else:
                evidence = self.knowledge_base.search_balanced(
                    artifact.workspace_id,
                    query,
                    artifact.document_ids,
                    top_k=min(30, max(4, len(artifact.document_ids) * per_document)),
                    per_document=per_document,
                )
            evidence_limit = (
                12 if artifact.artifact_type in {"slide_deck", "video_overview"} else 16
            )
            evidence = self._select_generation_evidence(evidence, limit=evidence_limit)
            if not evidence:
                raise ValueError("No searchable evidence was found in the selected sources")
            artifact = self.artifacts.save(
                artifact.model_copy(update={"stage": "retrieval", "progress": 25})
            )
            self.artifacts.record_event(
                artifact.workspace_id,
                artifact.artifact_id,
                stage="retrieval",
                status="completed",
                message="Source evidence retrieved",
                current=len(evidence),
                total=len(evidence),
                details={"document_count": len(artifact.document_ids)},
            )
            cancelled = self._cancelled_artifact(artifact)
            if cancelled is not None:
                return cancelled
            citations, context = self._context(
                evidence,
                max_text_chars=(
                    1_200
                    if artifact.artifact_type == "slide_deck"
                    else 1_400
                    if artifact.artifact_type == "video_overview"
                    else 1_600
                ),
            )
            agent_contract = ""
            if artifact.artifact_type == "slide_deck":
                self.artifacts.record_event(
                    artifact.workspace_id,
                    artifact.artifact_id,
                    stage="planning",
                    status="running",
                    message="Visual narrative planning started",
                    current=0,
                    total=1,
                )
                # The composer, not retrieval chunk count, owns narrative selection.
                # A deterministic slide-per-evidence plan forced irrelevant chunks into
                # automatic decks and made the LLM pad the story. Manual counts remain
                # explicit constraints in the public options and prompt.
                artifact = self.artifacts.save(
                    artifact.model_copy(
                        update={
                            "options": {
                                key: value
                                for key, value in artifact.options.items()
                                if not key.startswith("_agent_")
                            }
                        }
                    )
                )
            elif artifact.artifact_type == "video_overview":
                self.artifacts.record_event(
                    artifact.workspace_id,
                    artifact.artifact_id,
                    stage="planning",
                    status="running",
                    message="Video scene planning started",
                    current=0,
                    total=1,
                )
                video_plan = self._plan_autonomous_video(artifact, evidence)
                serialized_plan = self._serialize_video_plan(video_plan)
                artifact = self.artifacts.save(
                    artifact.model_copy(
                        update={
                            "options": {
                                **artifact.options,
                                "_agent_scene_count": video_plan.scene_count,
                                "_agent_video_plan": serialized_plan,
                            }
                        }
                    )
                )
                agent_contract = (
                    "\n\nAutonomous video planning contract (follow exactly; do not pad):\n"
                    + json.dumps(serialized_plan, ensure_ascii=False)
                )
            if artifact.artifact_type in {"slide_deck", "video_overview"}:
                artifact = self.artifacts.save(
                    artifact.model_copy(update={"stage": "planning", "progress": 35})
                )
                self.artifacts.record_event(
                    artifact.workspace_id,
                    artifact.artifact_id,
                    stage="planning",
                    status="completed",
                    message="Production plan ready",
                    current=1,
                    total=1,
                )
            artifact = self.artifacts.save(
                artifact.model_copy(
                    update={"status": "generating", "stage": "provider_attempt", "progress": 40}
                )
            )
            status = self._model_status()
            attempt_id = self.artifacts.begin_attempt(
                artifact.workspace_id,
                artifact.artifact_id,
                stage="provider",
                provider=status.get("provider"),
                model=status.get("active_model"),
            )
            self.artifacts.record_event(
                artifact.workspace_id,
                artifact.artifact_id,
                stage="provider_attempt",
                status="running",
                message="Generation provider attempt started",
                current=0,
                total=1,
                details={
                    "provider": status.get("provider"),
                    "model": status.get("active_model"),
                },
            )
            result = self._run_output(
                artifact,
                instructions=self._instructions(artifact) + agent_contract,
                user_input=context,
            )
            cancelled = self._cancelled_artifact(artifact)
            if cancelled is not None:
                return cancelled
            result = self._complete_output(artifact, context, result)
            self.artifacts.finish_attempt(attempt_id, status="completed")
            attempt_id = None
            artifact = self.artifacts.save(
                artifact.model_copy(update={"stage": "provider_complete", "progress": 70})
            )
            self.artifacts.record_event(
                artifact.workspace_id,
                artifact.artifact_id,
                stage="provider_attempt",
                status="completed",
                message="Generation provider attempt completed",
                current=1,
                total=1,
            )
            # A provider can return syntactically valid JSON that still violates the
            # presentation contract (for example, a title-only slide). Give decks one
            # bounded corrective pass instead of turning a recoverable draft into a
            # user-visible terminal failure.
            repair_attempts = 2 if artifact.artifact_type == "slide_deck" else 3
            for repair_attempt in range(repair_attempts):
                try:
                    data, markdown, title = self._decode_output(artifact, result.text)
                    break
                except (json.JSONDecodeError, ValueError) as error:
                    if (
                        artifact.artifact_type not in _STRUCTURED_TYPES
                        or repair_attempt == repair_attempts - 1
                    ):
                        raise
                    result = self._repair_structured_output(artifact, context, result, error)
            if artifact.artifact_type == "video_overview" and artifact.options.get(
                "_agent_video_plan"
            ):
                data = {**data, "agent_plan": artifact.options["_agent_video_plan"]}
            status = self._model_status()
            cancelled = self._cancelled_artifact(artifact)
            if cancelled is not None:
                return cancelled
            visual_plan = artifact.artifact_type in {"slide_deck", "video_overview"}
            final_progress = 80 if visual_plan else 100
            completed = self.artifacts.save(
                artifact.model_copy(
                    update={
                        "status": "generating" if visual_plan else "ready",
                        "stage": "render_queued" if visual_plan else "ready",
                        "progress": final_progress,
                        "title": artifact.title
                        if artifact.title_is_custom
                        else title or artifact.title,
                        "content_markdown": markdown,
                        "data": data,
                        "options": {
                            key: value
                            for key, value in artifact.options.items()
                            if not key.startswith("_agent_")
                        },
                        "citations": citations,
                        "provider": status.get("provider"),
                        "model": status.get("active_model"),
                        "error": None,
                    }
                )
            )
            self.artifacts.record_event(
                artifact.workspace_id,
                artifact.artifact_id,
                stage=("package" if final_progress == 80 else "completion"),
                status=("completed" if final_progress == 100 else "running"),
                message=(
                    "Studio artifact completed"
                    if final_progress == 100
                    else "Production plan packaged for rendering"
                ),
                current=1,
                total=1,
            )
            return completed
        except Exception as error:
            if attempt_id is not None:
                self.artifacts.finish_attempt(
                    attempt_id,
                    status="failed",
                    safe_error=type(error).__name__,
                )
            cancelled = self._cancelled_artifact(artifact)
            if cancelled is not None:
                return cancelled
            failed = self.artifacts.save(
                artifact.model_copy(
                    update={
                        "status": "failed",
                        "stage": "failed",
                        "error": f"{type(error).__name__}: {str(error)[:240]}",
                    }
                )
            )
            self.artifacts.record_event(
                artifact.workspace_id,
                artifact.artifact_id,
                stage=failed.stage,
                status="failed",
                message="Studio generation failed",
                current=failed.progress,
                total=100,
                details={"error_type": type(error).__name__},
            )
            return failed

    def get(self, workspace_id: str, artifact_id: str) -> StudioArtifact:
        return self.artifacts.get(workspace_id, artifact_id)

    def list(self, workspace_id: str) -> list[StudioArtifact]:
        self.workspaces.get(workspace_id)
        return self.artifacts.list(workspace_id)

    def request_cancel(self, workspace_id: str, artifact_id: str) -> StudioArtifact:
        """Persist a cancellation request that every Studio job observes."""
        artifact = self.artifacts.get(workspace_id, artifact_id)
        if artifact.status == "cancelled":
            return artifact
        if artifact.status in {"ready", "failed", "script_ready", "plan_ready"}:
            raise ValueError("Only an active Studio request can be cancelled")
        return self.artifacts.request_cancel(workspace_id, artifact_id)

    def _find(self, artifact_id: str, workspace_id: str | None) -> StudioArtifact:
        if workspace_id:
            return self.artifacts.get(workspace_id, artifact_id)
        for workspace in self.workspaces.list():
            try:
                return self.artifacts.get(workspace.workspace_id, artifact_id)
            except KeyError:
                continue
        raise KeyError(f"Unknown studio artifact: {artifact_id}")

    def _cancelled_artifact(self, artifact: StudioArtifact) -> StudioArtifact | None:
        current = self.artifacts.get(artifact.workspace_id, artifact.artifact_id)
        if current.status == "cancelled" or current.data.get("cancel_requested"):
            return current
        return None

    @staticmethod
    def _select_generation_evidence(
        evidence: Sequence[Evidence],
        *,
        limit: int,
    ) -> list[Evidence]:
        """Keep structured generation prompts bounded without losing source diversity."""
        buckets: dict[str, list[Evidence]] = {}
        for item in evidence:
            source_id = str(item.document_id or item.paper_id or item.filename or "unknown")
            buckets.setdefault(source_id, []).append(item)
        selected: list[Evidence] = []
        while len(selected) < limit and any(buckets.values()):
            for bucket in buckets.values():
                if bucket and len(selected) < limit:
                    selected.append(bucket.pop(0))
        return selected

    @staticmethod
    def _context(
        evidence: Sequence[Evidence],
        *,
        max_text_chars: int | None = None,
    ) -> tuple[list[StudioCitation], str]:
        citations = []
        blocks = []
        for index, item in enumerate(evidence, start=1):
            label = f"S{index}"
            filename = item.filename or item.paper_title
            citations.append(
                StudioCitation(
                    label=label,
                    document_id=item.document_id or item.paper_id,
                    filename=filename,
                    page_start=item.page_start,
                    page_end=item.page_end,
                    section=item.section,
                )
            )
            pages = (
                str(item.page_start)
                if item.page_start == item.page_end
                else f"{item.page_start}-{item.page_end}"
            )
            text = item.text.strip()
            if max_text_chars is not None and len(text) > max_text_chars:
                text = text[:max_text_chars].rsplit(" ", 1)[0].rstrip(" ,;:") + "..."
            blocks.append(f"[{label}] {filename} | pages {pages} | {item.section}\n{text}")
        return citations, "\n\n".join(blocks)

    @staticmethod
    def _retrieval_query(artifact: StudioArtifact) -> str:
        """Build the evidence query from the user's actual creative brief.

        Presentation retrieval used to ignore ``focus`` and spread a generic query
        evenly across every selected document. That made bibliography and unrelated
        course pages compete with the user's topic. Keep the generic type vocabulary
        only as a secondary recall hint.
        """
        user_focus = " ".join(
            str(artifact.options.get(key) or "").strip()
            for key in ("focus", "custom_deck_brief", "custom_instructions")
            if str(artifact.options.get(key) or "").strip()
        )
        if user_focus:
            return user_focus
        if artifact.title_is_custom:
            return artifact.title
        return studio_workflow_registry().plan(artifact.artifact_type).retrieval_focus

    @staticmethod
    def _plan_autonomous_deck(
        artifact: StudioArtifact,
        evidence: Sequence[Evidence],
    ) -> DeckPlan:
        planning_evidence = []
        for index, item in enumerate(evidence, start=1):
            label = f"S{index}"
            planning_evidence.append(
                {
                    "id": label,
                    "topic": StudioService._deck_planning_topic(item, artifact.title),
                    "claim": item.text,
                    "citations": [label],
                    "kind": item.section_type,
                    "importance": max(0.0, min(1.0, (item.similarity + 1) / 2)),
                }
            )
        strategy = str(artifact.options.get("slide_count_strategy") or "auto")
        planner_options = {
            **artifact.options,
            "planning_mode": "autonomous" if strategy == "auto" else "guided",
            "content_density": artifact.options.get("content_depth") or "auto",
            "language": artifact.language,
            "title": artifact.title,
        }
        return plan_deck(planning_evidence, planner_options)

    @staticmethod
    def _deck_planning_topic(evidence: Evidence, fallback: str) -> str:
        """Keep source document structure out of visible slide headlines.

        Retrieval sections such as ``Results`` and a paper's bibliographic
        title help ranking, but they are not audience-facing presentation
        language. A concise claim-derived subject is a safer planning seed;
        the model can then turn it into a natural headline.
        """
        section = str(evidence.section or "").strip()
        if section and not _GENERIC_DECK_SOURCE_SECTION.fullmatch(section):
            return section
        return StudioService._deck_claim_headline(evidence.text, fallback=fallback)

    @staticmethod
    def _deck_claim_headline(value: str, *, fallback: str = "") -> str:
        text = re.sub(r"\[(?:S\d+)(?:\s*[,;]\s*S\d+)*\]", " ", str(value or ""))
        text = re.sub(r"https?://\S+", " ", text)
        text = re.sub(r"\s+", " ", text).strip(" -_:;,.\n\t")
        headline = re.split(r"[.!?؟؛:\n]", text, maxsplit=1)[0].strip()
        if len(headline) > 96:
            headline = headline[:96].rsplit(" ", 1)[0].strip()
        return headline or fallback

    @staticmethod
    def _serialize_agent_plan(plan: DeckPlan) -> dict[str, Any]:
        slides = []
        for slide in plan.slides:
            media_request = None
            if slide.media_request is not None:
                media_request = {
                    "query": slide.media_request.query,
                    "asset_types": list(slide.media_request.asset_types),
                    "provider_policy": list(slide.media_request.provider_policy),
                    "require_api": True,
                    "allow_generated": False,
                }
            if slide.role.value == "case_study":
                resolved_media_layout = "case_study"
            elif slide.role.value == "quote":
                resolved_media_layout = "quote_photo"
            else:
                resolved_media_layout = "editorial_split"
            slides.append(
                {
                    "id": slide.slide_id,
                    "role": slide.role.value,
                    "title": slide.title,
                    "objective": slide.objective,
                    "layout": slide.layout,
                    "layout_if_media_resolves": resolved_media_layout
                    if media_request is not None
                    else None,
                    "evidence_ids": list(slide.evidence_ids),
                    "citations": list(slide.citations),
                    "content_density": slide.content_density.value,
                    "media_request": media_request,
                }
            )
        return {
            "mode": plan.mode.value,
            "slide_count": plan.slide_count,
            "content_density": plan.content_density.value,
            "media_density": plan.media_density.value,
            "slides": slides,
            "warnings": [
                {"code": warning.code, "message": warning.message}
                for warning in plan.warnings
            ],
            "rules": [
                "Use exactly this many substantive slides in autonomous mode.",
                "When media_request exists, use its query, set media_required=true, and use "
                "layout_if_media_resolves; the renderer will accept only a verified API asset.",
                "Never substitute generated, local, mock, or placeholder media.",
                "A chart is allowed only when its numeric labels and series are copied from the "
                "listed evidence and chart citations are supplied.",
            ],
        }

    @staticmethod
    def _autonomous_deck_fallback(
        artifact: StudioArtifact,
        evidence: Sequence[Evidence],
    ) -> dict[str, Any] | None:
        """Build an emergency evidence deck without exposing planner instructions.

        This path intentionally keeps only audience-facing source excerpts. Planner
        objectives, evidence labels, and production roles are private control data and
        must never appear on a rendered slide.
        """
        if artifact.artifact_type != "slide_deck":
            return None
        plan = artifact.options.get("_agent_plan")
        planned_slides = plan.get("slides") if isinstance(plan, dict) else None
        if not isinstance(planned_slides, list) or not planned_slides:
            return None

        source_text = {
            f"S{index}": StudioService._deck_excerpt(item.text)
            for index, item in enumerate(evidence, start=1)
        }
        slides = []
        for index, planned in enumerate(planned_slides, start=1):
            if not isinstance(planned, dict):
                return None
            planned_title = str(planned.get("title") or "").strip()
            citations = [
                str(item).strip()
                for item in planned.get("citations") or []
                if str(item).strip()
            ]
            excerpts = [source_text[label] for label in citations if source_text.get(label)]
            body = excerpts[0] if excerpts else ""
            if index == 1 and not body:
                body = (
                    "مروری مستند بر شواهد منتخب و نتیجه‌های اصلی آن‌ها"
                    if artifact.language == "fa"
                    else "A source-grounded overview of the selected evidence and its findings"
                )
            title = StudioService._deck_fallback_title(
                planned_title,
                body,
                fallback=artifact.title,
            )
            if not title or not body:
                return None
            media_request = planned.get("media_request")
            media_query = (
                str(media_request.get("query") or "").strip()
                if isinstance(media_request, dict)
                else ""
            )
            items: list[dict[str, str]] = []
            layout = "big_statement"
            media_layout = str(planned.get("layout_if_media_resolves") or "").strip()
            slides.append(
                {
                    "id": str(planned.get("id") or f"slide-{index:02d}"),
                    "layout": layout,
                    "kicker": "",
                    "title": title,
                    "subtitle": "",
                    "body": body,
                    "items": items,
                    "image_queries": [media_query] if media_query else [],
                    "citations": citations,
                    "layout_if_media_resolves": media_layout if media_query else "",
                    "media_fallback_layout": layout,
                    "media_required": False,
                }
            )
        return {
            "title": artifact.title,
            "subtitle": "",
            "narrative": "",
            "slides": slides,
            "generation_warnings": [
                "The model returned an invalid slide JSON draft; the validated autonomous plan "
                "was materialized directly from selected-source evidence."
            ],
        }

    @staticmethod
    def _deck_excerpt(value: str, *, limit: int = 420) -> str:
        text = re.sub(r"\s+", " ", str(value or "")).strip()
        if len(text) <= limit:
            return text
        clipped = text[:limit].rsplit(" ", 1)[0].strip()
        return f"{clipped}..." if clipped else text[:limit]

    @staticmethod
    def _deck_fallback_title(title: str, body: str, *, fallback: str) -> str:
        """Avoid showing a retrieval heading when a provider draft is unusable."""
        candidate = str(title or "").strip()
        source_like = bool(
            _GENERIC_DECK_SOURCE_SECTION.fullmatch(candidate)
            or re.search(
                r"https?://|\[[^\]]+\]\([^)]*\)|\b(?:doi|arxiv|publication)/",
                candidate,
                re.I,
            )
            or len(candidate) > 96
        )
        if candidate and not source_like:
            return candidate
        return StudioService._deck_claim_headline(body, fallback=candidate or fallback)

    @staticmethod
    def _plan_autonomous_video(
        artifact: StudioArtifact,
        evidence: Sequence[Evidence],
    ) -> VideoPlan:
        planning_evidence = []
        for index, item in enumerate(evidence, start=1):
            label = f"S{index}"
            planning_evidence.append(
                {
                    "id": label,
                    "topic": item.section or item.paper_title or artifact.title,
                    "claim": item.text,
                    "citations": [label],
                    "kind": item.section_type,
                    "importance": max(0.0, min(1.0, (item.similarity + 1) / 2)),
                }
            )
        strategy = str(artifact.options.get("scene_count_strategy") or "auto")
        planner_options = {
            **artifact.options,
            "planning_mode": "autonomous" if strategy == "auto" else "guided",
            "language": artifact.language,
            "title": artifact.title,
        }
        return plan_video(planning_evidence, planner_options)

